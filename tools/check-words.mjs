// ユーザーへ送る文の言葉づかいを検査する（CLAUDE.md §15・`arch/report-check.md`）。
// 使い方: node tools/check-words.mjs <下書きのファイル>
//
// ⚠️2026-09-08にユーザーが「わからない用語が多い」と指摘して作った。実例：
// 「前へ行く択が安くなる」「消耗だけ満額」——どちらもこちらの頭の中の比喩で、
// 何が何に対して安いのか、何の額が満ちているのかが文中のどこにも書かれていなかった。
// ⭐読み手の前提は「このゲームを遊んだことがない人。競馬用語は通じる」。
//
// ⚠️競馬の言葉は対象外（ユーザーは競馬を知っている。2026-09-08に明示）。
// この検査は**言葉の一覧との照合だけ**。意味が通るかどうかは判定できないので、
// `arch/report-check.md`のサブエージェント検査と両方を通すこと。

import fs from "node:fs";

// A：そのまま使わない。必ず具体的な言葉に書き換える。
// 「何が」「何に対して」「どれだけ」が文中に無いまま雰囲気で通じてしまう言い方。
const BANNED = [
  ["安く|割安|割高|高くつ|お得|コストが", "→ 何が どれだけ 増える/減る のかを数量で書く"],
  ["満額|全額|フルに|目一杯|全開で|上限いっぱい", "→ 何の上限か、その値はいくつかを書く"],
  ["効く|効き|効か(?!った)|効け|効果的|刺さ", "→ 何がどう変わるのかを書く"],
  ["レバレッジ|解像度|構造的|次元|土台|地盤|肝(?![臓])|落とし込|寄り添|手触り|温度感|世界観|立て付け|親和性", "→ 比喩。具体語に置き換える"],
  ["最適化|チューニング|ブラッシュアップ", "→ 何をどう変えたのかを書く"],
  ["ちゃんと|きちんと|うまく|いい感じ|適切に|しっかり|きれいに", "→ どうなっていれば良いのかを書く"],
  ["など|等(?![級高速価分身々])|といった|系(?![統列])", "→ 省略せずに全部並べる（CLAUDE.md §8）"],
];

// B：開発の言葉。初めて出すときは、同じ文か次の文で必ず1行の説明を付ける。
const DEV = [
  "シード", "乱数", "フォーク", "クランプ", "パラメータ", "引数", "定数", "変数",
  "関数", "リファクタ", "デバッグ", "ビルド", "コミット", "プッシュ", "ブランチ",
  "リポジトリ", "DOM", "CSS", "レンダリング", "クロージャ", "インスタンス",
  "中央値", "標準偏差", "正規化", "線形", "係数", "積分", "ステップ", "オフセット",
  "swing", "effect", "aggression", "ramp", "seed", "px/s", "m/s",
  // ⚠️2026-09-08にユーザーから「掃引とは? 上が開きすぎとは何？ 床を入れるとは？ 帯とは？」と
  // 4語まとめて問われた。どれも説明せずに使っていた。
  "掃引", "床を入れ", "帯", "上が開", "クランプ", "しきい値", "閾値", "係数", "分散", "収束",
];

// ⚠️競馬の言葉は検査しない（2026-09-08にユーザーが「俺がわかるから制限しなくていい」と明示）。
// ⚠️ただしこれは**ユーザーへ送る文**の話。ゲーム画面に出す言葉はCLAUDE.md §7のまま
// （競馬を知らない人が読んで分かる言葉だけ）。

const path = process.argv[2];
if (!path) { console.error("使い方: node tools/check-words.mjs <下書きのファイル>"); process.exit(2); }
const lines = fs.readFileSync(path, "utf8").split("\n");

let banned = 0;
const firstUse = new Map(); // 言葉 → 初めて出た行番号

// ⭐「」で囲んだ部分は検査しない——**その言葉自体を話題にしている**ときのため
// （この検査のルールを説明する文や、過去の自分の文を引用して直す文で必ず出てくる）。
// ⚠️「」で囲めば禁止語を使えてしまうが、囲むこと自体が「これは引用だ」という表明なので
// 抜け道としては扱わない。
const withoutQuotes = (line) => line.replace(/「[^」]*」/g, "");

console.log("=== A：書き換えが必要な言い方 ===");
lines.forEach((line0, i) => {
  const line = withoutQuotes(line0);
  for (const [pat, note] of BANNED) {
    const m = line.match(new RegExp(pat));
    if (m) { console.log(`  ${i + 1}行目「${m[0]}」 ${note}`); banned += 1; }
  }
});
if (banned === 0) console.log("  なし");

for (const [label, list] of [["B：開発の言葉", DEV]]) {
  console.log(`\n=== ${label}（初出の行に説明が付いているか目で確かめる） ===`);
  let n = 0;
  for (const w of list) {
    const i = lines.findIndex((l) => withoutQuotes(l).includes(w));
    if (i >= 0) { console.log(`  ${i + 1}行目  ${w}`); firstUse.set(w, i + 1); n += 1; }
  }
  if (n === 0) console.log("  なし");
}

// D：根拠の無い数字。「目安として」「候補」「〜か〜」で数字を並べている行に、
// 根拠を示す言葉（実測／実データ／出典／測った／◯レース／ユーザー決定）が無ければ止める。
// ⚠️2026-09-08にユーザーが「35mとか45mは根拠がある数字？」と指摘して作った。
// 数字を出すときは必ず「値（根拠：何をどう測ったか／どのデータか）」の形にする。
const GROUND = /実測|実データ|出典|測った|測り|レース|seed|通り|JRA|ユーザー(が|の)決|根拠[：:]|根拠(なし|が無い|は無い|がない|はない|がありません)/;
const PROPOSAL = /目安として|候補|案[ABCＡＢＣ]?[：:]|どれくらいに|にするか|くらい|前後/;
// 数え上げ（N行・N本・N件・N箇所・Nつ）は提案の数字ではないので、行にそれしか数字が無ければ見ない。
const COUNT_ONLY = (line) => line.replace(/\d+(行|本|件|箇所|つ|の候補)/g, "").search(/\d/) < 0;
let ungrounded = 0;
console.log("\n=== D：根拠の無い数字（提案の行に根拠が書いてあるか） ===");
lines.forEach((line0, i) => {
  const line = withoutQuotes(line0);
  if (/\d/.test(line) && PROPOSAL.test(line) && !GROUND.test(line) && !COUNT_ONLY(line)) {
    console.log(`  ${i + 1}行目 → 数字に根拠が無い。「値（根拠：…）」の形にするか、根拠が無いと明記する`);
    ungrounded += 1;
  }
});
if (ungrounded === 0) console.log("  なし");
console.log(`\nAが${banned}件・Dが${ungrounded}件。両方0になるまで書き換えること。`);
console.log("Bは、初出の行に1行の説明が付いているかを自分で確かめる（この検査は数えるだけ）。");
process.exit(banned + ungrounded > 0 ? 1 : 0);
